/**
 * Writes src/data/articleIndex.js: the card-level fields of every article,
 * without the article bodies. The home page imports this instead of the full
 * articles.js, so three preview cards do not cost 85KB of article HTML.
 *
 * Run after adding or editing an article: node scripts/build-article-index.mjs
 * (src/__tests__/articleIndex.test.js fails when the index is stale.)
 */
import { writeFile } from 'node:fs/promises';
import { articles } from '../src/data/articles.js';

export const INDEX_FIELDS = ['id', 'slug', 'title', 'displayTitle', 'excerpt', 'category', 'date', 'readTime', 'icon', 'featured'];

export const toIndex = (list) => list.map((a) => Object.fromEntries(INDEX_FIELDS.filter((k) => k in a).map((k) => [k, a[k]])));

const body = `// GENERATED by scripts/build-article-index.mjs from src/data/articles.js. Do not edit by hand.
export const articleIndex = ${JSON.stringify(toIndex(articles), null, 2)};

export const getRecentArticleCards = (limit = 3) =>
  [...articleIndex].sort((a, b) => new Date(b.date) - new Date(a.date)).slice(0, limit);
`;

if (process.argv[1] && process.argv[1].endsWith('build-article-index.mjs')) {
  await writeFile(new URL('../src/data/articleIndex.js', import.meta.url), body);
  console.log(`articleIndex.js: ${articles.length} articles`);
}
